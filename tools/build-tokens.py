#!/usr/bin/env python3
"""Generate apps/desktop/src/styles/tokens.css from docs/design-system/tokens.json.
Run: python3 tools/build-tokens.py   (tokens.css is generated; never edit it by hand)"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
t = json.loads((root / "docs/design-system/tokens.json").read_text())
light, dark, other = [], [], []
for x in t["color"]["tokens"] + t["shadow"]["tokens"]:
    light.append(f"  --{x['name']}: {x['value']['light']};")
    dark.append(f"  --{x['name']}: {x['value']['dark']};")
for fam, val in t.items():
    if isinstance(val, dict) and "tokens" in val and fam not in ("color", "shadow"):
        other.append(f"  /* {fam} */")
        other += [f"  --{x['name']}: {x['value']};" for x in val["tokens"]]
other.append("  /* type families */")
other += [f"  --font-{k}: {v};" for k, v in t["type"]["families"].items()]
types = []
for g in t["type"]["groups"]:
    for s in g["styles"]:
        d = [f"font-family: var(--font-{s.get('family', g['family'])})", f"font-size: {s['fontSize']}", f"line-height: {s['lineHeight']}",
             f"font-weight: {s['fontWeight']}", f"letter-spacing: {s['letterSpacing']}"]
        if s.get("textTransform"): d.append(f"text-transform: {s['textTransform']}")
        if s.get("fontFeatureSettings"): d.append(f"font-feature-settings: {s['fontFeatureSettings']}")
        types.append(f".t-{s['name']} {{ {'; '.join(d)}; }}")
nl = "\n"
css = f"""/* GENERATED by tools/build-tokens.py from docs/design-system/tokens.json. Do not edit. */
:root, [data-theme="light"] {{
{nl.join(light)}
}}
[data-theme="dark"] {{
{nl.join(dark)}
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{nl.join('  ' + l for l in dark)}
  }}
}}
:root {{
{nl.join(other)}
}}
/* Type styles: one class per token in tokens.json (t-display, t-body, t-note-body, ...). */
{nl.join(types)}
"""
(root / "apps/desktop/src/styles/tokens.css").write_text(css)
print("wrote tokens.css", len(css))
